"""Build markdown tables from sweep_out/results/runs.tsv -> sweep_out/results/tables.md
usage: python3 -I make_tables.py sweep_out
Values are means over seeds (n in the table); ranges are min..max over seeds where shown.
"""
import sys, csv
from collections import defaultdict
import numpy as np

BASE = dict(leak=0.5, cost=0.03, D=0.3, phi=0.2, o_resp=0.2)
root = sys.argv[1]
rows = list(csv.DictReader(open(f"{root}/results/runs.tsv"), delimiter="\t"))


def f(x):
    try:
        return float(x)
    except Exception:
        return np.nan


def label(r):
    d = [f"{k}={r[k]}" for k, v in BASE.items() if abs(f(r[k]) - v) > 1e-9]
    return ", ".join(d) if d else "base"


groups = defaultdict(list)
for r in rows:
    groups[(r["block"], label(r), f(r["iota"]))].append(r)
order = sorted(groups, key=lambda k: (k[0], k[1] != "base", k[1], k[2]))


def m(rs, k, nd=2):
    v = [f(r[k]) for r in rs]
    v = [x for x in v if x == x]
    return f"{np.mean(v):.{nd}f}" if v else "–"


def rng_(rs, k, nd=2):
    v = [f(r[k]) for r in rs]
    v = [x for x in v if x == x]
    return f"{min(v):.{nd}f}..{max(v):.{nd}f}" if v else "–"


def table(title, cols, blocks=("A", "E"), note=""):
    out = [f"### {title}", ""]
    if note:
        out += [note, ""]
    out.append("| block | config | ι | n | " + " | ".join(c[0] for c in cols) + " |")
    out.append("|" + "---|" * (4 + len(cols)))
    for key in order:
        if key[0] not in blocks:
            continue
        rs = groups[key]
        out.append(f"| {key[0]} | {key[1]} | {key[2]:g} | {len(rs)} | " +
                   " | ".join(c[1](rs) for c in cols) + " |")
    return "\n".join(out) + "\n"


M = lambda k, nd=2: (lambda rs: m(rs, k, nd))
R = lambda k, nd=2: (lambda rs: rng_(rs, k, nd))


def cnt(k, pred):
    return lambda rs: f"{sum(pred(f(r[k])) for r in rs)}/{len(rs)}"


md = ["# bq_lattice revised sweep tables (auto-generated by make_tables.py from results/runs.tsv)", ""]
md.append(table("T1. Ground truth: P-all over tested kept sets (cell-weighted, last two sample times, scope all)", [
    ("autonomous", M("nec_autonomous")), ("not plexi (d≤1, no simple cycle ≥3 witness)", M("nec_not_plexi")),
    ("plexi fan-in", M("nec_fanin")), ("plexi cyclic", M("nec_cyclic")), ("plexi mixed", M("nec_mixed")),
    ("plexi any", M("nec_plexi_any")), ("plexi any range", R("nec_plexi_any")),
    ("unresolved (no feasible tested set)", M("nec_unresolved_no_feasible_set")),
    ("not viable in situ", M("nec_not_viable_in_situ")),
    ("realised d≥2", M("real_d2")),
    ("genome-autonomous that survive alone", M("genome_auto_survive_frac")),
    ("genome-dependent that survive alone", M("genome_dep_survive_alone_frac")),
    ("OX+ANX co-carriers", M("frac_cells_OX_and_ANX")), ("mean leaky carried", M("mean_leaky_carried")),
    ("euk cells", M("euk_cell_frac"))]))
md.append(table("T2. P2-like inference vs truth (MAG × time); resolved-only and [low, high] bounds", [
    ("prec", M("incomplete_prok_prec_res")), ("rec", M("incomplete_prok_rec_res")),
    ("prec low", M("incomplete_prok_prec_low")), ("prec high", M("incomplete_prok_prec_high")),
    ("rec low", M("incomplete_prok_rec_low")), ("rec high", M("incomplete_prok_rec_high")),
    ("rec fan-in truth", M("incomplete_prok_rec_fanin")), ("rec cyclic truth", M("incomplete_prok_rec_cyclic")),
    ("unresolved frac", M("incomplete_prok_frac_unres")),
    ("complete prec", M("complete_prok_prec_res")), ("complete rec", M("complete_prok_rec_res")),
    ("d bias", M("inc_d_bias", 3)), ("false absence HQ", M("false_absence_hq", 3)),
    ("false absence all", M("false_absence_all", 3))],
    note="Precision/recall are means over seeds that had at least one evaluable call (– = none)."))
md.append(table("T3. Mechanism statistics on synthetic observations (P2-like observer)", [
    ("I", M("I_incomplete_prok", 3)), ("I CI lo", M("I_incomplete_prok_lo", 3)), ("I CI hi", M("I_incomplete_prok_hi", 3)),
    ("I true genotypes", M("I_oracle_genotypes", 3)),
    ("Σ_leaky", M("Sigma_leaky_incomplete_prok", 3)), ("Σ_private", M("Sigma_private_incomplete_prok", 3)),
    ("prev leaky", M("prev_leaky_incomplete_prok")), ("prev private", M("prev_private_incomplete_prok")),
    ("Σ_inc", M("Sigma_inc_incomplete_prok", 3)),
    ("obs uncond", M("obs_uncond_incomplete_prok")), ("null uncond", M("exp_uncond_incomplete_prok")),
    ("O−E uncond", M("oe_uncond_incomplete_prok", 3)),
    ("obs cond", M("obs_cond_incomplete_prok")), ("null cond", M("exp_cond_incomplete_prok")),
    ("O−E cond", M("oe_cond_incomplete_prok", 3))],
    note="Σ is log(observed / expected) per-donor co-carriage against fixed-count column permutation."))
md.append(table("T4. P4: same recipient MAG × event in both fractions, equal weights", [
    ("units", M("p4_n_units", 0)), ("observer P−W", M("p4_obs_P_minus_W", 3)),
    ("observer, donor-standardised", M("p4_obs_donor_standardised", 3)),
    ("donors W", M("p4_mean_donors_W", 1)), ("donors P", M("p4_mean_donors_P", 1)),
    ("truth units", M("p4_n_truth_units", 0)), ("truth P−W (any plexi)", M("p4_truth_P_minus_W", 3)),
    ("truth P−W (fan-in)", M("p4_truth_fanin_P_minus_W", 3))]))
md.append(table("T5. Eukaryote contribution and prokaryote-only bias", [
    ("euk cells", M("euk_cell_frac")), ("euk share of uptake", M("euk_share_uptake")),
    ("feasible sets with euk", M("euk_frac_sets")),
    ("prok-only rec [low, high]", lambda rs: f"[{m(rs, 'incomplete_prok_rec_low')}, {m(rs, 'incomplete_prok_rec_high')}]"),
    ("prok-only unresolved", M("incomplete_prok_frac_unres")),
    ("with-euk rec [low, high]", lambda rs: f"[{m(rs, 'incomplete_all_rec_low')}, {m(rs, 'incomplete_all_rec_high')}]"),
    ("with-euk unresolved", M("incomplete_all_frac_unres")),
    ("complete+euk prec", M("complete_all_prec_res")), ("complete+euk rec", M("complete_all_rec_res"))],
    blocks=("E",)))
md.append(table("T6. Rare members of feasible sets and abundance distributions", [
    ("members in catalogue", M("member_in_catalogue")), ("detected (emergent)", M("member_detected_emergent")),
    ("detected (lognormal bg)", M("member_detected_lognormal")), ("detected (power-law bg)", M("member_detected_powerlaw")),
    ("in core", M("member_in_core_emergent")), ("d≤1 witness member outside core", M("witness_outside_core_emergent")),
    ("core-only prec", M("incomplete_prok_core_prec_res")), ("core-only rec", M("incomplete_prok_core_rec_res")),
    ("genotypes", M("n_genotypes", 0)), ("MAGs", M("n_mags", 0)),
    ("Vuong z (LN−PL)", M("abund_vuong_z_mean")), ("frac |z|>2", lambda rs: m(rs, "abund_frac_z_gt2")),
    ("PL α", M("abund_alpha")), ("top-10 share", M("abund_top10_share"))]))
md.append(table("T7. Runtime (s per run incl. counterfactuals, 8 concurrent workers, shared host)", [
    ("runtime", M("runtime_s", 0)), ("final cells", M("final_cells", 0))]))
open(f"{root}/results/tables.md", "w").write("\n".join(md))
print("\n".join(md))
